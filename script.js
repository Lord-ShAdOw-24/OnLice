function initCosmos(){
  const canvas=document.getElementById("cosmos-canvas");

  if(!canvas||!canvas.getContext)return;

  const ctx=canvas.getContext("2d");

  let width=0;
  let height=0;

  const particles=Array.from({length:110},()=>({
    x:Math.random(),
    y:Math.random(),
    r:Math.random()*1.5+.3,
    vx:(Math.random()-.5)*.00012,
    vy:(Math.random()-.5)*.00012,
    a:Math.random()*.45+.08,
    c:Math.random()>.5?"#008F7A":"#FF5A00"
  }));

  function resize(){
    width=canvas.width=window.innerWidth;
    height=canvas.height=window.innerHeight;
  }

  resize();

  window.addEventListener("resize",resize);

  function draw(){
    ctx.clearRect(0,0,width,height);

    particles.forEach(p=>{
      p.x+=p.vx;
      p.y+=p.vy;

      if(p.x<0)p.x=1;
      if(p.x>1)p.x=0;
      if(p.y<0)p.y=1;
      if(p.y>1)p.y=0;

      ctx.beginPath();
      ctx.arc(p.x*width,p.y*height,p.r,0,Math.PI*2);
      ctx.fillStyle=p.c;
      ctx.globalAlpha=p.a;
      ctx.fill();
    });

    ctx.globalAlpha=1;

    const glow1=ctx.createRadialGradient(
      width*.12,
      height*.12,
      0,
      width*.12,
      height*.12,
      Math.max(width,height)*.24
    );

    glow1.addColorStop(0,"rgba(0,143,122,.12)");
    glow1.addColorStop(1,"transparent");

    ctx.fillStyle=glow1;
    ctx.fillRect(0,0,width,height);

    const glow2=ctx.createRadialGradient(
      width*.88,
      height*.18,
      0,
      width*.88,
      height*.18,
      Math.max(width,height)*.2
    );

    glow2.addColorStop(0,"rgba(255,90,0,.10)");
    glow2.addColorStop(1,"transparent");

    ctx.fillStyle=glow2;
    ctx.fillRect(0,0,width,height);

    requestAnimationFrame(draw);
  }

  draw();
}

function animateCountersSafe(){
  document.querySelectorAll("[data-count]").forEach(element=>{
    if(element.dataset.animated==="1")return;

    element.dataset.animated="1";

    const target=Number(element.dataset.count||0);
    let current=0;

    const step=Math.max(target/45,.5);

    const timer=setInterval(()=>{
      current+=step;

      if(current>=target){
        element.textContent=target+(target===100?"%":"+");
        clearInterval(timer);
      }else{
        element.textContent=
          Math.floor(current)+(target===100?"%":"+");
      }
    },24);
  });
}

