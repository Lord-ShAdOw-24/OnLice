(function(){
  const canvas = document.getElementById("cosmos-canvas");

  if(!canvas || !canvas.getContext){
    return;
  }

  const ctx = canvas.getContext("2d");

  let W;
  let H;
  let particles = [];
  let frame = 0;

  const colors = [
    "#F5560B",
    "#0B6E63",
    "#14A392",
    "#FF8A45",
    "#0B121A"
  ];

  function resize(){
    W = canvas.width = window.innerWidth;
    H = canvas.height = window.innerHeight;
  }

  resize();

  window.addEventListener("resize",resize);

  class Particle{
    constructor(){
      this.reset();
    }

    reset(){
      this.x = Math.random()*W;
      this.y = Math.random()*H;
      this.r = Math.random()*1.8+0.3;
      this.vx = (Math.random()-0.5)*0.3;
      this.vy = (Math.random()-0.5)*0.3;
      this.alpha = Math.random()*0.68+0.12;
      this.color = colors[Math.floor(Math.random()*colors.length)];
      this.life = Math.random()*300+100;
      this.age = 0;
    }

    update(){
      this.x += this.vx;
      this.y += this.vy;
      this.age++;

      if(this.age > this.life){
        this.reset();
      }
    }

    draw(){
      ctx.save();

      ctx.globalAlpha =
        this.alpha *
        (1 - this.age/this.life);

      ctx.beginPath();

      ctx.arc(
        this.x,
        this.y,
        this.r,
        0,
        Math.PI*2
      );

      ctx.fillStyle = this.color;
      ctx.fill();

      ctx.restore();
    }
  }

  class Comet{
    constructor(){
      this.reset();
    }

    reset(){
      this.x = Math.random()*W;
      this.y = -50;
      this.len = Math.random()*120+60;
      this.speed = Math.random()*4+2;
      this.alpha = Math.random()*0.48+0.12;
      this.color = colors[Math.floor(Math.random()*colors.length)];
      this.angle = Math.PI/4+(Math.random()-0.5)*0.3;
      this.active = false;
      this.delay = Math.floor(Math.random()*500);
      this.t = 0;
    }

    update(){
      this.t++;

      if(this.t < this.delay){
        return;
      }

      if(!this.active){
        this.active = true;
      }

      this.x += Math.cos(this.angle)*this.speed;
      this.y += Math.sin(this.angle)*this.speed;

      if(this.y > H+100){
        this.reset();
      }
    }

    draw(){
      if(!this.active){
        return;
      }

      ctx.save();

      ctx.globalAlpha = this.alpha;

      const grad =
        ctx.createLinearGradient(
          this.x,
          this.y,
          this.x-Math.cos(this.angle)*this.len,
          this.y-Math.sin(this.angle)*this.len
        );

      grad.addColorStop(0,this.color);
      grad.addColorStop(1,"transparent");

      ctx.beginPath();

      ctx.moveTo(
        this.x,
        this.y
      );

      ctx.lineTo(
        this.x-Math.cos(this.angle)*this.len,
        this.y-Math.sin(this.angle)*this.len
      );

      ctx.strokeStyle = grad;
      ctx.lineWidth = 1.5;
      ctx.stroke();

      ctx.restore();
    }
  }

  for(let i=0;i<200;i++){
    particles.push(
      new Particle()
    );
  }

  const comets = [
    new Comet(),
    new Comet(),
    new Comet()
  ];

  const nebulae = [
    {x:0.2,y:0.15,r:300,c:"#0B6E63",a:0.065},
    {x:0.8,y:0.3,r:250,c:"#F5560B",a:0.06},
    {x:0.5,y:0.8,r:200,c:"#14A392",a:0.04},
    {x:0.1,y:0.7,r:180,c:"#F5560B",a:0.04}
  ];

  function drawNebulae(){
    nebulae.forEach(n => {
      const ox =
        Math.sin(frame*0.003+n.x)*30;

      const oy =
        Math.cos(frame*0.002+n.y)*20;

      const grad =
        ctx.createRadialGradient(
          n.x*W+ox,
          n.y*H+oy,
          0,
          n.x*W+ox,
          n.y*H+oy,
          n.r
        );

      grad.addColorStop(0,n.c);
      grad.addColorStop(1,"transparent");

      ctx.save();

      ctx.globalAlpha = n.a;
      ctx.fillStyle = grad;

      ctx.beginPath();

      ctx.arc(
        n.x*W+ox,
        n.y*H+oy,
        n.r,
        0,
        Math.PI*2
      );

      ctx.fill();

      ctx.restore();
    });
  }

  function loop(){
    frame++;

    ctx.clearRect(
      0,
      0,
      W,
      H
    );

    drawNebulae();

    particles.forEach(p => {
      p.update();
      p.draw();
    });

    comets.forEach(c => {
      c.update();
      c.draw();
    });

    requestAnimationFrame(loop);
  }

  loop();
})();

