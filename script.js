function setupFallbackImages(){
  document.querySelectorAll(".team-avatar-wrap,.project-logo-slot,.project-image-slot").forEach(container=>{
    const img=container.querySelector("img");
    const fallback=container.querySelector("span");

    if(!img)return;

    const hideFallback=()=>{
      img.style.display="none";
      if(fallback)fallback.style.display="flex";
    };

    const showImage=()=>{
      img.style.display="block";
      if(fallback)fallback.style.display="none";
    };

    img.addEventListener("error",hideFallback);

    if(img.complete&&img.naturalWidth===0){
      hideFallback();
    }else if(img.complete){
      showImage();
    }
  });
}

function setupTeamInitials(){
  document.querySelectorAll(".team-card").forEach(card=>{
    const nameElement=card.querySelector("h5");
    const fallback=card.querySelector(".team-initials");

    if(!nameElement||!fallback)return;

    const name=nameElement.textContent.trim();
    const parts=name.split(/\s+/).filter(Boolean);

    let letters="";

    if(parts.length>=2){
      letters=(parts[0][0]+parts[1][0]).toUpperCase();
    }else if(parts.length===1){
      letters=parts[0].slice(0,2).toUpperCase();
    }else{
      letters="--";
    }

    fallback.textContent=letters;
  });
}

