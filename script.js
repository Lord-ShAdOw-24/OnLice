function observeCardsSafe(){
  if(!("IntersectionObserver" in window)){
    document.querySelectorAll(".card,.section-title,.section-label,.project-feature,.process-step").forEach(el=>{
      el.classList.add("reveal-visible");
    });
    return;
  }

  const observer=new IntersectionObserver(entries=>{
    entries.forEach(entry=>{
      if(entry.isIntersecting){
        entry.target.classList.add("reveal-visible");
        observer.unobserve(entry.target);
      }
    });
  },{
    threshold:.08,
    rootMargin:"0px 0px -40px 0px"
  });

  document.querySelectorAll(".card,.section-title,.section-label,.project-feature,.process-step").forEach(el=>{
    if(!el.classList.contains("reveal"))el.classList.add("reveal");
    observer.observe(el);
  });
}

function initAboutCanvasSafe(id){
  const canvas=document.getElementById(id);

  if(!canvas||!canvas.getContext)return;

  const rect=canvas.getBoundingClientRect();
  const dpr=Math.min(window.devicePixelRatio||1,2);

  canvas.width=Math.max(1,rect.width*dpr);
  canvas.height=Math.max(1,rect.height*dpr);

  const ctx=canvas.getContext("2d");
  ctx.scale(dpr,dpr);

  const W=rect.width;
  const H=rect.height;

  let t=0;

  function draw(){
    ctx.clearRect(0,0,W,H);

    const base=ctx.createLinearGradient(0,0,W,H);
    base.addColorStop(0,"#08201d");
    base.addColorStop(.5,"#008F7A");
    base.addColorStop(1,"#FF5A00");

    ctx.fillStyle=base;
    ctx.fillRect(0,0,W,H);

    for(let i=0;i<6;i++){
      const x=W/2+Math.sin(t*.008+i*1.17)*W*.34;
      const y=H/2+Math.cos(t*.006+i*.83)*H*.32;
      const r=34+Math.sin(t*.014+i)*18;

      const glow=ctx.createRadialGradient(x,y,0,x,y,r);
      glow.addColorStop(0,"rgba(255,255,255,.18)");
      glow.addColorStop(1,"transparent");

      ctx.fillStyle=glow;
      ctx.beginPath();
      ctx.arc(x,y,r,0,Math.PI*2);
      ctx.fill();
    }

    t++;
    requestAnimationFrame(draw);
  }

  draw();
}

