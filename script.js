function renderSocialLinks(){
  const container =
    document.getElementById(
      "socialLinks"
    );

  if(!container){
    return;
  }

  container.innerHTML =
    SOCIAL_PLATFORMS
      .map(platform => {
        const external =
          platform.href &&
          platform.href !== "#";

        const target =
          external
            ? ' target="_blank" rel="noopener noreferrer"'
            : "";

        return `
          <a
            class="social-link"
            href="${platform.href}"
            ${target}
            title="${platform.name}"
            aria-label="${platform.name}"
          >
            <svg viewBox="0 0 24 24">
              ${platform.icon}
            </svg>
          </a>
        `;
      })
      .join("");
}

function setCopyrightYear(){
  const element =
    document.getElementById(
      "copyYear"
    );

  if(!element){
    return;
  }

  const startYear = 2024;
  const now =
    new Date().getFullYear();

  element.textContent =
    now > startYear
      ? `© ${startYear}–${now}`
      : `© ${startYear}`;
}

const revealObserver =
  new IntersectionObserver(
    entries => {
      entries.forEach(entry => {
        if(entry.isIntersecting){
          entry.target.classList.add(
            "revealed"
          );

          revealObserver.unobserve(
            entry.target
          );
        }
      });
    },
    {
      threshold:.12
    }
  );

function scheduleReveal(){
  const activePage =
    document.querySelector(
      ".page.active"
    );

  if(!activePage){
    return;
  }

  const groups =
    activePage.querySelectorAll(
      ".grid-3, .grid-2, .grid-4, .process-steps, #faqList"
    );

  groups.forEach(group => {
    Array.from(group.children)
      .forEach((child,i) => {
        if(
          !child.classList.contains(
            "reveal-item"
          )
        ){
          child.classList.add(
            "reveal-item"
          );

          child.style.transitionDelay =
            Math.min(
              i*80,
              320
            ) + "ms";
        }

        if(
          !child.classList.contains(
            "revealed"
          )
        ){
          revealObserver.observe(
            child
          );
        }
      });
  });

  activePage
    .querySelectorAll(
      ".stats-row, .contact-form, .contact-info, .about-visual"
    )
    .forEach(el => {
      if(
        !el.classList.contains(
          "reveal-item"
        )
      ){
        el.classList.add(
          "reveal-item"
        );
      }

      if(
        !el.classList.contains(
          "revealed"
        )
      ){
        revealObserver.observe(el);
      }
    });
}

